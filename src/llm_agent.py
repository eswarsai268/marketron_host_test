# UNIFIED CHAT & CAMPAIGN GENERATOR
# --------------------------------------------------

def generate_action_response(
    chat_history: list,
    cluster_name: str,
    top_category: str,
    price_sensitivity: str,
    user_prompt: str,
    segment_customer_count: int | None = None,
    segment_avg_spend: float | None = None,
    segment_avg_recency: float | None = None,
    segment_avg_frequency: float | None = None
):
    """
    Handles both UI button clicks and raw chat inputs, maintaining context.
    """
    
    # If starting a fresh chat, inject the powerful System Prompt first
    if not chat_history:
        segment_stats_context = ""

        if segment_customer_count is not None:
            segment_stats_context += (
                f" The segment currently contains "
                f"{segment_customer_count:,} customers."
            )

        if segment_avg_spend is not None:
            segment_stats_context += (
                f" Its average customer spend is "
                f"₹{segment_avg_spend:,.2f}."
            )

        rag_query = (
            f"Marketing strategy for the '{cluster_name}' customer segment. "
            f"Average recency: {segment_avg_recency if segment_avg_recency is not None else 'unknown'} days. "
            f"Average purchase frequency: {segment_avg_frequency if segment_avg_frequency is not None else 'unknown'} orders."
            + (f" Average customer spend: ₹{segment_avg_spend:,.2f}." if segment_avg_spend is not None else "")
        )
        rag_context = retrieve_marketing_context(rag_query)

        print("\n========== RAG DEBUG ==========")
        print(f"RAG query: {rag_query}")
        print(f"RAG context retrieved: {bool(rag_context)}")
        print(f"RAG context length: {len(rag_context)} characters")
        print("================================\n", flush=True)

        rag_context_block = ""

        if rag_context:
            rag_context_block = (
                "\n\nRelevant marketing knowledge:\n"
                + rag_context
                + "\n\nUse this knowledge as supporting guidance. "
                  "Do not mention the knowledge base or retrieval process."
            )
        
        system_prompt = (
    f"You are an elite AI Marketing Strategist. Your current client is focusing on the "
    f"'{cluster_name}' segment" 
    + segment_stats_context
    + (f", who frequently buy '{top_category}'." if top_category != "General Merchandise" else ".")
    + (f" This segment's discount behavior profile is: '{price_sensitivity}'." if price_sensitivity and price_sensitivity != "None" else "")
    + "\n\n"
    "Rules:\n"
    "1. If asked for a strategy, provide a highly detailed, tactical step-by-step plan (What to do & How to execute it), "
    "grounded in the specific behavioral traits of the segment (e.g., purchase frequency, spend level, engagement, churn risk).\n"
    "2. If asked for copy (email/ads), provide high-converting, personalized text with a hook and CTA.\n"
    "3. Do NOT output fluff like 'Here is your strategy'. Just output the raw requested content formatted cleanly in Markdown.\n"
    "4. Adapt both tone AND tactics to the segment (e.g., high-value/loyal segments get exclusive, reward-driven "
    "approaches; at-risk or dormant segments get urgent, win-back approaches; steady/average segments get "
    "engagement-building approaches).\n"
    + ("5. Use the discount behavior profile to decide whether to include coupon codes or price-based incentives: "
       "if the profile suggests a full-price/non-discount buyer, do NOT include coupon codes or percentage-off offers — "
       "lead with value, exclusivity, or urgency instead. If the profile suggests deal-seeking or promo-driven behavior, "
       "coupon codes and discount framing are appropriate and should be included.\n"
       if price_sensitivity and price_sensitivity != "None" else
       "5. No discount behavior profile was provided — use your best judgment on whether coupon codes or "
       "price-based incentives fit the segment's other traits, without assuming a specific discount preference.\n")
    + ("6. No specific product category was provided — do NOT invent or reference one. Base the entire "
       "strategy purely on the segment's behavioral profile." if top_category == "General Merchandise" else "")
        + rag_context_block   
)
        chat_history.append({"role": "system", "content": system_prompt})

    # Only append the user turn if the caller hasn't already added it as the most recent message
    if not chat_history or chat_history[-1]["role"] != "user" or chat_history[-1]["content"] != user_prompt:
        chat_history.append({"role": "user", "content": user_prompt})
    
    # Prune to save context window and avoid token limits
    chat_history = prune_chat_history(chat_history)
    
    # Generate the AI response using the traffic-aware router
    generated_text = _call_llm_with_fallback(chat_history)
    
    # Append the AI's response to maintain conversation memory
    chat_history.append({"role": "assistant", "content": generated_text})
    
    return generated_text, chat_history