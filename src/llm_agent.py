# LLM FALLBACK ROUTER (The "Traffic-Aware" Engine)
# --------------------------------------------------

def _call_llm_with_fallback(messages):
    """
    Tries Gemini models first. If a model hits a traffic error or times out, it switches.
    If Gemini fails entirely, it repeats the exact same logic for Groq.
    """
    from groq import Groq
    from google import genai
    from google.genai import types  
    
    # 1. Configuration
    groq_models = [ "llama-3.3-70b-versatile", # Flagship: Incredibly smart, perfect Gemini alternative
                    "llama-3.1-8b-instant",    # Fallback 1: Lightning fast, highly reliable
                    "gemma2-9b-it"             # Fallback 2: Google's excellent open-weight model
    ]
    groq_keys = [os.getenv(f"GROQ_KEY_{i}") for i in range(1, 5)]

    gemini_models = ["gemini-3.5-flash-lite", "gemini-2.5-flash", "gemini-2.5-flash-lite"]
    gemini_keys = [os.getenv(f"GEMINI_KEY_{i}") for i in range(1, 5)]

    # --- PHASE 1: GEMINI EXECUTION ---
    gemini_messages = []
    system_instruction = None

    for msg in messages:
        if msg["role"] == "system":
            system_instruction = msg["content"]
        else:
            role = "model" if msg["role"] == "assistant" else "user"
            gemini_messages.append(
                {
                    "role": role,
                    "parts": [{"text": msg["content"]}]
                }
            )

    for model_name in gemini_models:
        for key_idx, key in enumerate(gemini_keys, start=1):
            if not key:
                continue

            try:
                print(f"🔄 Attempting Gemini: {model_name} (Key {key_idx})...",flush=True)

                client = genai.Client(
                    api_key=key,
                    http_options=types.HttpOptions(
                        timeout=15000
                    )
                )

                response = client.models.generate_content(
                    model=model_name,
                    contents=gemini_messages,
                    config=types.GenerateContentConfig(
                        system_instruction=system_instruction
                    )
                )

                print(f"✅ SUCCESS: Response generated by {model_name}",flush=True)

                return response.text

            except Exception as e:
                print(
                    f"❌ ERROR on Gemini {model_name}: {e}",
                    flush=True
                )

                error_msg = str(e).lower()

                if (
                    "429" in error_msg
                    or "quota" in error_msg
                    or "rate limit" in error_msg
                ):
                    break

                continue

    # --- PHASE 2: GROQ EXECUTION ---
    for model in groq_models:
        for key_idx, key in enumerate(groq_keys, start=1):
            if not key:
                continue
            try:
                # ---> FIX 1: Log BEFORE the attempt
                print(f"🔄 Attempting Groq: {model} (Key {key_idx})...", flush=True)
                
                # ---> FIX 2: Hard 8-second timeout injected here
                client = Groq(api_key=key, timeout=8.0)
                response = client.chat.completions.create(
                    model=model,
                    messages=messages,
                    temperature=0.7,
                    max_tokens=800
                )
                
                print(f"✅ SUCCESS: Response generated by {model}")
                return response.choices[0].message.content
                
            except Exception as e:
                print(f"❌ ERROR on Groq {model}: {e}", flush=True)
                error_msg = str(e).lower()
                if "429" in error_msg or "rate limit" in error_msg or "too many requests" in error_msg:
                    break 
                continue

    # --- PHASE 3: TOTAL FAILURE ---
    raise RuntimeError("CRITICAL ERROR: All Groq and Gemini models/keys exhausted or timed out.")
        
        


# --------------------------------------------------
# CHAT HISTORY PRUNER
# --------------------------------------------------

def prune_chat_history(
    chat_history,
    max_messages=8,
    max_chars=18000
):
    """
    Keep the system message and the newest conversation turns
    while enforcing both message and approximate token budgets.

    Rough rule:
        ~4 characters ≈ 1 token for ordinary English text.
    """

    if not chat_history:
        return chat_history

    system_message = chat_history[0]
    remaining = chat_history[1:]

    # First limit by message count.
    remaining = remaining[-(max_messages - 1):]

    # Then limit by approximate character budget.
    selected = []
    total_chars = 0

    for message in reversed(remaining):
        content = message.get("content", "")
        message_chars = len(content)

        if (
            selected
            and total_chars + message_chars > max_chars
        ):
            break

        selected.append(message)
        total_chars += message_chars

    selected.reverse()

    return [system_message] + selected


